/**
 * What may never be released without a person (#674, D-418): the one data file of the release policy's sensitivity rules. Code applies it
 * (`release-policy.ts`); a model never edits it and can only add to it for one Scroll (a raise, never a lowering).
 *
 * The owner's categories are medicine, health, law, finance, political or religious history, current events and safety. Two things put a
 * Scroll in one: the catalogue (the system its topic belongs to) and the words it uses. Both lean toward holding: a false match sends a Scroll
 * to a person, who reads it as they do today, and a miss would publish a sensitive Scroll unread. A longer list is a safe change; a shorter
 * one, or a new topic in the catalogue that this file does not name, is the owner's to decide, with a new `SENSITIVITY_VERSION`.
 */

/** The version of this file's rules. Changing any list or number below is a new version, so a decision can be traced to the rules it was made under. */
export const SENSITIVITY_VERSION = 'release-sensitivity.v1';

export const SENSITIVE_CATEGORIES = [
  'medicine',
  'health',
  'law',
  'finance',
  'political_history',
  'religious_history',
  'current_events',
  'safety',
] as const;
export type SensitiveCategory = (typeof SENSITIVE_CATEGORIES)[number];

/**
 * Catalogue systems whose every topic is sensitive, with the categories they fall under. Exact system ids from the library plan.
 * - `human-body`: how organs and the immune system work is medicine and health to a reader who acts on it.
 * - `history`: code cannot tell political or religious history from other history, so every history topic waits for a person.
 */
export const SENSITIVE_SYSTEMS: Readonly<Record<string, readonly SensitiveCategory[]>> = {
  'human-body': ['medicine', 'health'],
  history: ['political_history', 'religious_history'],
};

/**
 * The keys of a stored Scroll document whose values are not the Scroll's words: its identity, versions, measures, integrity hash and the references one part
 * makes to another. Their values (a UUID, a hash, `s3`) are skipped when the document is scanned, because a run of four digits inside an identifier would
 * read as a year. Every other string of the document is scanned, so a field this list does not know is read like prose: the scan errs toward holding.
 */
export const NON_PROSE_KEYS: ReadonlySet<string> = new Set([
  'schemaVersion',
  'limitsVersion',
  'assetId',
  'explanationUnitId',
  'id',
  'stop',
  'anchorStop',
  'revealStage',
  'smallPrintAside',
  'measures',
  'integrity',
]);

/**
 * The years that read as the present or the near future: a Scroll that names one of 2023 to 2100 is about something recent or projected,
 * which is current events and ages out. Numeric policy values, versioned with the file.
 */
export const RECENT_YEAR_FROM = 2023;
export const RECENT_YEAR_TO = 2100;

