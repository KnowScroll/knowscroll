import { oc } from '@orpc/contract';
import { z } from 'zod';
import { ClientCapabilities, LocalId, ScrollDocument } from './content.js';
import {
  LegacySavedItemSchema,
  SavedPageRequestSchema,
  SavedPageResponseSchema,
  savedListErrors,
  savedListProblemResponses,
} from './saved-page.js';
import { AssetIdSchema, CommandIdSchema, UuidSchema } from './ids.js';
import {
  ActivateOfferRequestSchema,
  ActivateOfferResponseSchema,
  NavigationOutcomeSchema,
  OpenDiscoveryRequestSchema,
  OpenRevisitRequestSchema,
} from './navigation.js';

/**
 * `POST /v1/actions`: an explicit action on a Reel or Scroll. `commandId` is generated by the
 * client once per user intent and reused on retry; the same ID with different content is refused
 * with `COMMAND_KEY_REUSED`. `assetRevision` is the revision the client showed.
 */
export const ApplyActionRequestSchema = z.object({
  commandId: CommandIdSchema,
  kind: z.enum(['save', 'unsave', 'like', 'unlike', 'hide']),
  target: z.object({ assetId: AssetIdSchema, assetRevision: z.number().int().min(1) }),
  /**
   * Optional explicit encounter linkage: own activated exposure, same epoch and exact revision.
   * Without it this is asset preference only; never infer a latest encounter or qualification.
   */
  exposureId: UuidSchema.optional(),
});

export const SavedActionResponseSchema = z.object({
  commandId: CommandIdSchema,
  actionId: UuidSchema,
  kind: z.enum(['save', 'unsave']),
  assetId: AssetIdSchema,
  assetRevision: z.number().int().min(1),
  saved: z.boolean(),
  changed: z.boolean(),
  /**
   * The universe revision after this command (its catch-up watermark; compare with hints). A
   * command that changed nothing a client reads does not advance it. Clients keep the highest
   * revision they have seen from any source.
   */
  revision: z.number().int().min(0),
  /** True when this response is the stored outcome of an earlier identical request. */
  replayed: z.boolean(),
});

/** Like and Hide are separate action channels; neither changes the current saved state. */
export const ApplyActionResponseSchema = z.union([
  SavedActionResponseSchema,
  z.strictObject({
    commandId: CommandIdSchema,
    actionId: UuidSchema,
    kind: z.enum(['like', 'unlike', 'hide']),
    assetId: AssetIdSchema,
    assetRevision: z.number().int().min(1),
    liked: z.boolean(),
    hidden: z.boolean(),
    changed: z.boolean(),
    revision: z.number().int().min(0),
    replayed: z.boolean(),
  }),
]);

export type ApplyActionRequest = z.infer<typeof ApplyActionRequestSchema>;
export type ApplyActionResponse = z.infer<typeof ApplyActionResponseSchema>;

export const applyActionContract = oc
  .route({ method: 'POST', path: '/v1/actions', successStatus: 200, tags: ['experience'] })
  .input(ApplyActionRequestSchema)
  .output(ApplyActionResponseSchema);

/** Original list (default50, maximum100) stays compatible. Newly reserved paging fields cannot silently strip
 * into the first legacy page. Unrelated legacy unknown fields still strip. */
export const LegacyListSavedRequestSchema = z.object({
  limit: z
    .string()
    .regex(/^(?:[1-9][0-9]?|100)$/)
    .optional(),
  pagination: z.never().optional(),
  filter: z.never().optional(),
  cursor: z.never().optional(),
});
export const LegacyListSavedResponseSchema = z.object({
  revision: z.number().int().min(0),
  items: z.array(LegacySavedItemSchema),
  pagination: z.never().optional(),
  consistency: z.never().optional(),
  scope: z.never().optional(),
  filter: z.never().optional(),
  limit: z.never().optional(),
  continuation: z.never().optional(),
});
/** GET query values remain strings; no defaults, coercion or transforms at the wire boundary. */
export const ListSavedRequestSchema = z.union([SavedPageRequestSchema, LegacyListSavedRequestSchema]);
export const ListSavedResponseSchema = z.union([SavedPageResponseSchema, LegacyListSavedResponseSchema]);
export type ListSavedResponse = z.infer<typeof ListSavedResponseSchema>;

/** Declaration only: new consumers must explicitly require SavedPageResponseSchema and compare
 * scope/filter/limit to the initiating request; a legacy reply is not a complete page. */
export const listSavedContract = oc
  .route({
    method: 'GET',
    path: '/v1/saved',
    successStatus: 200,
    tags: ['experience'],
    spec: savedListProblemResponses,
  })
  .errors(savedListErrors)
  .input(ListSavedRequestSchema)
  .output(ListSavedResponseSchema);

/**
 * `POST /v1/experience/open`: open an admitted Scroll for the signed-in person, which creates an
 * **exposure**, the lineage root of this encounter: exposure ID, asset revision, origin and what
 * the client can render. The origin says how the person arrived; `direct` is an address (the
 * `/scroll/<assetId>` route). Opening is not consumption: nothing is evidence until the reading is
 * observed and qualified. `commandId` is minted once per intent and reused on retry; the same ID
 * with different content is `COMMAND_KEY_REUSED`. An asset that does not exist, is withdrawn, or
 * is not a Scroll answers `ASSET_NOT_FOUND`; none of those writes a receipt. The same route also
 * declares Composer discovery (see navigation.ts); the interim consumer refuses it explicitly.
 */
export const DirectOpenExposureRequestSchema = z.object({
  commandId: CommandIdSchema,
  target: z.object({ kind: z.enum(['scroll', 'reel']), assetId: AssetIdSchema }),
  origin: z.object({ kind: z.literal('direct') }),
  /** What this client build can render; the document is negotiated for it (D-012). */
  capabilities: ClientCapabilities,
});

export const DirectOpenExposureResponseSchema = z.object({
  /** Reserved for Composer outcomes; they must not downgrade into a legacy exposure. */
  status: z.never().optional(),
  commandId: CommandIdSchema,
  exposureId: UuidSchema,
  assetId: AssetIdSchema,
  /** The immutable revision this exposure presents. */
  assetRevision: z.number().int().min(1),
  kind: z.enum(['scroll', 'reel']),
  /** The universe revision after this command (it changes nothing a client reads, so unchanged). */
  revision: z.number().int().min(0),
  /** True when this response is the stored outcome of an earlier identical request. */
  replayed: z.boolean(),
});

/** Direct open keeps its exposure result; discovery/revisit use Composer session outcomes. */
export const OpenExposureRequestSchema = z.union([
  OpenDiscoveryRequestSchema,
  OpenRevisitRequestSchema,
  DirectOpenExposureRequestSchema,
]);
export const OpenExposureResponseSchema = z.union([NavigationOutcomeSchema, DirectOpenExposureResponseSchema]);

export type OpenExposureRequest = z.infer<typeof OpenExposureRequestSchema>;
export type OpenExposureResponse = z.infer<typeof OpenExposureResponseSchema>;

export const openExposureContract = oc
  .route({ method: 'POST', path: '/v1/experience/open', successStatus: 200, tags: ['experience'] })
  .input(OpenExposureRequestSchema)
  .output(OpenExposureResponseSchema);

/**
 * `POST /v1/experience/activate`: the exposure's article became the active reading surface (it is
 * rendered and in front). Activation is the lineage the recorder's observations require; it does
 * not say anything was seen (visibility is observed separately). Idempotent: activating an active
 * exposure answers its original activation time. `NOT_FOUND` for an exposure that is not the
 * caller's (an unknown and a foreign exposure are indistinguishable).
 */
export const DirectActivateExposureRequestSchema = z.object({
  /** Newly reserved discriminator: all other unknown legacy fields still strip as before. */
  target: z.never().optional(),
  commandId: CommandIdSchema,
  exposureId: UuidSchema,
});

export const DirectActivateExposureResponseSchema = z.object({
  /** Reserved for offer activation so malformed offer lineage cannot downgrade. */
  sessionId: z.never().optional(),
  commandId: CommandIdSchema,
  exposureId: UuidSchema,
  activatedAt: z.iso.datetime(),
  revision: z.number().int().min(0),
  replayed: z.boolean(),
});

/**
 * Offer commands are distinct from the interim direct activation. The legacy object keeps its
 * unknown-field stripping behavior except for the newly reserved `target` discriminator. Its
 * presence must satisfy the offer schema; malformed/mixed bodies cannot downgrade to direct.
 */
export const ActivateExposureRequestSchema = z.union([ActivateOfferRequestSchema, DirectActivateExposureRequestSchema]);
export const ActivateExposureResponseSchema = z.union([
  ActivateOfferResponseSchema,
  DirectActivateExposureResponseSchema,
]);

export type ActivateExposureRequest = z.infer<typeof ActivateExposureRequestSchema>;
export type ActivateExposureResponse = z.infer<typeof ActivateExposureResponseSchema>;

export const activateExposureContract = oc
  .route({ method: 'POST', path: '/v1/experience/activate', successStatus: 200, tags: ['experience'] })
  .input(ActivateExposureRequestSchema)
  .output(ActivateExposureResponseSchema);

/**
 * `GET /v1/experience/exposures/{exposureId}/document`: the consumer document the exposure
 * presents, negotiated for the capabilities the client declared when it opened (D-012). Immutable
 * per revision. It never carries claims, sources, production records or any other internal
 * provenance. `degradedEssential` lists essential blocks the client will see only as fallback text,
 * so it can say "this part needs an app update". `NOT_FOUND` for an exposure that is not the
 * caller's.
 */
export const ExposureDocumentRequestSchema = z.object({ exposureId: UuidSchema });

export const ExposureDocumentResponseSchema = z.object({
  exposureId: UuidSchema,
  assetId: AssetIdSchema,
  assetRevision: z.number().int().min(1),
  document: ScrollDocument,
  degradedEssential: z.array(z.object({ blockId: LocalId, originalType: z.string() })).max(80),
});

export type ExposureDocumentResponse = z.infer<typeof ExposureDocumentResponseSchema>;

export const exposureDocumentContract = oc
  .route({
    method: 'GET',
    path: '/v1/experience/exposures/{exposureId}/document',
    successStatus: 200,
    tags: ['experience'],
  })
  .input(ExposureDocumentRequestSchema)
  .output(ExposureDocumentResponseSchema);
